conversations = {}

def get_ai_response(user_id, user_text):
    current_time = time.time()
    timeout_seconds = 1800

    if user_id in conversations:
        last_time = conversations[user_id]["last_time"]
        if current_time - last_time > timeout_seconds:
            del conversations[user_id]

    if user_id not in conversations:
        chat = client.chats.create(
            model="gemini-2.5-flash",
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_PROMPT,
                temperature=0.7,
            )
        )
        conversations[user_id] = {"chat": chat, "last_time": current_time}

    if len(conversations) > 500:
        conversations.clear()

    conversations[user_id]["last_time"] = current_time
    chat = conversations[user_id]["chat"]

    max_retries = 3

    for attempt in range(max_retries):
        try:
            response = chat.send_message(user_text)
            return response.text

        except Exception as e:
            error_msg = str(e)

            if "429" in error_msg or "quota" in error_msg.lower():
                print(f"[Внимание] Лимит запросов. Ждем 5 секунд... (Попытка {attempt + 1} из {max_retries})")
                time.sleep(5)
                continue
            else:
                print(f"Ошибка Gemini: {e}")
                return "Извините, сейчас я немного перегружен. Пожалуйста, подождите минутку и напишите снова. 🙏"

    return "Ой, у нас сейчас очень много обращений! 😅 Пожалуйста, подождите буквально минуту и продублируйте ваш вопрос."
